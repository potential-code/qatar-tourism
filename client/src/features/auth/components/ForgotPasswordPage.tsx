import { Link } from '@tanstack/react-router'
import { Mail } from 'lucide-react'
import { useState } from 'react'
import { z } from 'zod'
import { SimulatedTag } from '@/components/layout'
import { useAppForm } from '@/hooks/useAppForm'
import { authClient } from '@/lib/auth-client'
import { AuthShell } from './AuthShell'
import { FormAlert } from './FormAlert'

const schema = z.object({ email: z.email('Enter a valid email address') })

/** Forgot password. The answer is the same whether or not the account exists. */
export function ForgotPasswordPage() {
  const [sentTo, setSentTo] = useState<string | null>(null)
  const [error, setError] = useState(false)
  const form = useAppForm({
    defaultValues: { email: '' },
    validators: { onSubmit: schema },
    onSubmit: async ({ value }) => {
      setError(false)
      const { error: failure } = await authClient.requestPasswordReset({
        email: value.email.trim(),
        redirectTo: `${window.location.origin}/reset-password`,
      })
      if (failure) {
        setError(true)
        return
      }
      setSentTo(value.email.trim())
    },
  })

  return (
    <AuthShell image="/images/official/zulal-spa.jpg" alt="A calm spa interior">
      <div className="grid gap-2">
        <h1 className="font-display font-light text-4xl">Reset your password</h1>
        <p className="text-muted-foreground">
          Enter your account email and we will create a reset link.
        </p>
      </div>
      {sentTo ? (
        <div className="grid gap-4">
          <FormAlert tone="success">
            If an account exists for {sentTo}, a reset link has been generated by the demo mail
            service.
          </FormAlert>
          <p className="flex flex-wrap items-center gap-2 text-muted-foreground text-sm">
            <SimulatedTag label="Demo email" />
            Demo accounts use fictional example.com addresses, so no real inbox receives the link.
            Ask the demo facilitator for the shared demo password.
          </p>
        </div>
      ) : (
        <form
          noValidate
          className="grid gap-4"
          onSubmit={(event) => {
            event.preventDefault()
            void form.handleSubmit()
          }}
        >
          {error ? (
            <FormAlert>We could not send the request. Try again in a few minutes.</FormAlert>
          ) : null}
          <form.AppField name="email" validators={{ onBlur: schema.shape.email }}>
            {(field) => (
              <field.TextField label="Email" type="email" autoComplete="email" icon={Mail} />
            )}
          </form.AppField>
          <form.AppForm>
            <form.SubmitButton className="h-12 w-full text-base">
              Create reset link
            </form.SubmitButton>
          </form.AppForm>
        </form>
      )}
      <Link to="/login" className="w-fit text-teal text-sm underline-offset-4 hover:underline">
        Back to sign in
      </Link>
    </AuthShell>
  )
}
